"""Seeded front-matter values for comparing the charter reader with a real YAML parser.

`tests/vectors/charter-yaml.json` holds what PyYAML 6 read for each of these, generated by
`python tests/yaml_corpus.py > tests/vectors/charter-yaml.json` with PyYAML installed. The test
compares the reader against that file, so CI needs no YAML library.
"""
import random

TOKENS = ["a", "src/**", "10h", "1", "010", "0x1f", "1e3", ".5", "10.", "yes", "No", "on", "True", "null",
          "~", "none", "2026-11-10", "10:30", "-1", "+1", "1_000", "it's", "#", "x #y", ":", "a:b", "a: b",
          "\"q\"", "'s'", "\"a, b\"", "é", "*", "&a", "!t", "|", ">", "%", "@", "`", "?", "-", "grok-4.7",
          "y", "OFF", ".inf", "0", "00", "1:2:3", "2026-11-10T10:00:00Z", "a  b", "\"\\u00e9\"", "'it''s'"]


def value(rng, depth=0):
    roll = rng.random()
    if depth < 3 and roll < 0.25:
        return "[" + ", ".join(value(rng, depth + 1) for _ in range(rng.randint(0, 3))) + "]"
    if depth < 3 and roll < 0.45:
        keys = rng.sample(["k", "role", "usd", "a-b", "x"], rng.randint(0, 3))
        return "{" + ", ".join(f"{k}: {value(rng, depth + 1)}" for k in keys) + "}"
    return " ".join(rng.choice(TOKENS) for _ in range(rng.choice([1, 1, 1, 2])))


def corpus(seed=2026, n=800):
    rng = random.Random(seed)
    return [value(rng) for _ in range(n)]


def yaml_view(v):
    """PyYAML's result as JSON, with any non-JSON type marked so the reader must refuse it."""
    if isinstance(v, bool) or v is None or isinstance(v, (int, str)):
        return v
    if isinstance(v, list):
        return [yaml_view(x) for x in v]
    if isinstance(v, dict):
        if not all(isinstance(k, str) for k in v):
            return {"__type__": "non-string key"}
        return {k: yaml_view(x) for k, x in v.items()}
    return {"__type__": type(v).__name__}


if __name__ == "__main__":
    import json

    import yaml

    out = []
    for text in corpus():
        try:
            got = yaml.safe_load(f"v: {text}\n")
            expected = yaml_view(got["v"]) if isinstance(got, dict) and set(got) == {"v"} else {"__type__": "shape"}
        except yaml.YAMLError:
            expected = {"__type__": "error"}
        out.append({"text": text, "yaml": expected})
    print(json.dumps(out, ensure_ascii=True, indent=0))
